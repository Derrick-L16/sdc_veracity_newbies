import { test, expect } from './isolated-test'
import { enterDemo, loginDemo } from './demo-helpers'

test('demo entry, change role, persisted sessions and unsaved work', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('navigation', { name: 'Main' })).toHaveCount(0)
  await expect(page.getByTestId('select-demo-role')).toHaveValue('')
  await expect(page.getByRole('heading', { name: 'Login', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Log in', exact: true })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Role summaries' })).toHaveCount(0)
  await expect(page.getByText('Demo login — no email or password required.', { exact: true })).toHaveCount(0)
  expect((await page.request.get('/api/backend/state')).status()).toBe(401)
  await page.getByTestId('button-enter-demo').click()
  await expect(page.getByText('Choose a role to continue.', { exact: true })).toBeVisible()
  await page.route('**/api/backend/session', r => r.fulfill({ status: 503, json: { error: 'Demo service unavailable.' } }))
  await enterDemo(page, 'owner')
  await expect(page.getByText('Demo service unavailable.', { exact: true })).toBeVisible()
  await expect(page.getByTestId('button-enter-demo')).toBeEnabled()
  await page.unroute('**/api/backend/session')
  await enterDemo(page, 'owner')
  await expect(page).toHaveURL(/\/reports$/)
  await page.reload()
  await expect(page.getByTestId('stat-countSubmissions')).toBeVisible()
  // A saved session must not bypass the entry page when visiting the root.
  await page.goto('/')
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByTestId('select-demo-role')).toHaveValue('')
  await expect(page.getByRole('navigation', { name: 'Main' })).toHaveCount(0)
  await page.reload()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByTestId('select-demo-role')).toBeVisible()
  await enterDemo(page, 'owner')
  await expect(page).toHaveURL(/\/reports$/)
  await page.goto('/inbox')
  await expect(page.getByRole('link', { name: 'Account', exact: true })).toHaveCount(0)
  await expect(page.getByRole('radio')).toHaveCount(0)
  await page.route('**/api/backend/session/end', r => r.fulfill({ status: 503, json: { error: 'Please retry changing role.' } }))
  await page.getByRole('button', { name: /^Role:/ }).click()
  await page.getByTestId('button-change-role').click()
  await expect(page.getByText('Please retry changing role.', { exact: true })).toBeVisible()
  await expect(page).toHaveURL(/\/inbox$/)
  await expect(page.getByRole('button', { name: /Role: Owner/ })).toBeVisible()
  await page.unroute('**/api/backend/session/end')
  await page.getByRole('button', { name: /^Role:/ }).click()
  await page.getByTestId('button-change-role').click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/backend/state')).status()).toBe(401)
  await page.goBack()
  await expect(page).toHaveURL(/\/login(?:\?|$)/)
  await page.goto('/login')
  await enterDemo(page, 'staff')
  await expect(page).toHaveURL(/\/work$/)
  await page.goto('/count')
  await page.getByLabel('Note (optional)', { exact: true }).fill('Unsaved inventory note')
  page.once('dialog', d => d.dismiss())
  await page.getByRole('button', { name: /^Role:/ }).click()
  await page.getByTestId('button-change-role').click()
  await expect(page).toHaveURL(/\/count$/)
  await expect(page.getByLabel('Note (optional)', { exact: true })).toHaveValue('Unsaved inventory note')
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: /^Role:/ }).click()
  await page.getByTestId('button-change-role').click()
  await expect(page).toHaveURL(/\/login$/)
  await enterDemo(page, 'manager')
  await expect(page).toHaveURL(/\/inbox$/)
  await page.goto('/count')
  await expect(page.getByLabel('Note (optional)', { exact: true })).toHaveValue('')
  expect(errors).toEqual([])
})

test('deep links, safe destinations, mobile and session expiry', async ({ page, baseURL }) => {
  await loginDemo(page, 'manager')
  const headers = { Origin: baseURL! }
  const productId = `deep-link-${Date.now()}`
  expect((await page.request.post('/api/backend/imports', {
    data: { kind: 'products', rows: [{ id: productId, name: productId, recorded: 10 }] }, headers,
  })).ok()).toBe(true)
  const count = await page.request.post('/api/backend/counts', {
    data: { productId, counted: 8 }, headers,
  })
  expect(count.ok()).toBe(true)
  const { id } = await count.json()
  expect(id).toBeTruthy()
  expect((await page.request.post('/api/backend/session/end', {
    data: {}, headers,
  })).ok()).toBe(true)
  await page.goto(`/cases/${id}?v=1`)
  await expect(page).toHaveURL(/\/login\?next=/)
  await enterDemo(page, 'manager')
  await expect(page).toHaveURL(new RegExp(`/cases/${id}\\?v=1$`))
  await page.reload()
  await expect(page).toHaveURL(new RegExp(`/cases/${id}\\?v=1$`))
  await page.request.post('/api/backend/session/end', { data: {}, headers })
  await page.goto('/login?next=https%3A%2F%2Fexample.com')
  await enterDemo(page, 'staff')
  await expect(page).toHaveURL(/\/work$/)
  await page.request.post('/api/backend/session/end', { data: {}, headers })
  // Polling notices a session revoked in another tab without restoring Manager.
  await expect(page).toHaveURL(/\/login(?:\?|$)/, { timeout: 15000 })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByTestId('select-demo-role')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'generated-artifacts/demo-login-mobile.jpg', fullPage: true })
  expect((await page.request.get('/api/backend/state')).status()).toBe(401)
})
